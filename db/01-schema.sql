COMMENT ON COLUMN password_reset_token.is_used IS 'Boolean flag indicating whether token has already been consumed (REQ-4.1-F04, SCO-05)';
COMMENT ON COLUMN password_reset_token.used_at IS 'Timestamp when password reset was completed (REQ-4.1-F04, SCO-05)';

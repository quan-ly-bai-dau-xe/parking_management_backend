-- 11.1. View v_revenue_statistics (Revenue Statistics by Month / Quarter / Year)
-- References: SRS 4.7.1 (REQ-4.7.1-F01..F05, ACT-4.7.1-A01, image19, OQ-11, Rule 05)
CREATE VIEW v_revenue_statistics AS
WITH all_revenue_records AS (
    -- Revenue from initial ticket issuance
    SELECT
        EXTRACT(YEAR FROM created_at)::INTEGER AS report_year,
        EXTRACT(QUARTER FROM created_at)::INTEGER AS report_quarter,
        EXTRACT(MONTH FROM created_at)::INTEGER AS report_month,
        price AS revenue_amount,
        1 AS ticket_sales_count,
        0 AS renewal_count
    FROM ticket

    UNION ALL

    -- Revenue from ticket renewal extensions
    SELECT
        EXTRACT(YEAR FROM renewal_date)::INTEGER AS report_year,
        EXTRACT(QUARTER FROM renewal_date)::INTEGER AS report_quarter,
        EXTRACT(MONTH FROM renewal_date)::INTEGER AS report_month,
        additional_price AS revenue_amount,
        0 AS ticket_sales_count,
        1 AS renewal_count
    FROM ticket_renewal
)
SELECT
    report_year,
    report_quarter,
    report_month,
    SUM(ticket_sales_count)::BIGINT AS total_tickets_sold,
    SUM(renewal_count)::BIGINT AS total_renewals,
    SUM(revenue_amount)::NUMERIC(12, 2) AS total_revenue
FROM all_revenue_records
GROUP BY report_year, report_quarter, report_month
ORDER BY report_year DESC, report_month DESC;

COMMENT ON VIEW v_revenue_statistics IS 'All-time aggregated financial revenue metrics grouped by Month, Quarter, and Year, preserving 100% historical sales (SRS 4.7.1 REQ-4.7.1-F05; date-filtered range statistics are provided by fn_stat_revenue_by_period)';


-- 11.2. View v_vehicle_traffic_daily (Daily Vehicle Traffic Flow)
-- References: SRS 4.7.2 (REQ-4.7.2-F03 Daily traffic chart, image20)
CREATE VIEW v_vehicle_traffic_daily AS
SELECT
    entry_time::DATE AS traffic_date,
    COUNT(*)::BIGINT AS total_entries,
    COUNT(exit_time)::BIGINT AS total_exits,
    COUNT(*) FILTER (WHERE exit_time IS NULL)::BIGINT AS currently_parked_count
FROM vehicle_entry_exit_log
GROUP BY entry_time::DATE
ORDER BY traffic_date DESC;

COMMENT ON VIEW v_vehicle_traffic_daily IS 'All-time daily vehicle entry and exit traffic volume statistics (SRS 4.7.2 REQ-4.7.2-F03; date-filtered traffic statistics are provided by fn_stat_vehicles_by_day)';


-- 11.3. View v_slot_occupancy_by_floor (Parking Lot Slot Occupancy Rate by Floor)
-- References: SRS 4.7.2 (REQ-4.7.2-F04 Occupancy chart by floor, image20, OQ-63)
CREATE VIEW v_slot_occupancy_by_floor AS
WITH slot_live_status AS (
    SELECT
        s.id AS slot_id,
        s.floor_number,
        s.status AS stored_status,
        -- Operational check: exclude maintenance slots from available/occupied calculation
        (s.status <> 'MAINTENANCE') AS is_operational,
        -- Live physical presence check: open entry session currently in slot
        EXISTS (
            SELECT 1 
            FROM vehicle_entry_exit_log l 
            WHERE l.slot_id = s.id 
              AND l.exit_time IS NULL
        ) AS has_open_session,
        -- Dynamic ticket window check: active ticket currently in effect
        EXISTS (
            SELECT 1 
            FROM ticket t 
            WHERE t.slot_id = s.id 
              AND t.deleted_at IS NULL 
              AND t.status = 'ACTIVE' 
              AND CURRENT_TIMESTAMP >= t.effective_from 
              AND CURRENT_TIMESTAMP < t.effective_to
        ) AS has_active_ticket
    FROM parking_slot s
    WHERE s.deleted_at IS NULL
),
floor_aggregated AS (
    SELECT
        floor_number,
        COUNT(slot_id)::BIGINT AS total_slots,
        -- Available slots: operational and neither occupied by open session nor reserved by active ticket
        COUNT(slot_id) FILTER (
            WHERE is_operational AND NOT has_open_session AND NOT has_active_ticket
        )::BIGINT AS available_slots,
        -- Occupied slots: operational and occupied by open session OR reserved by active ticket
        COUNT(slot_id) FILTER (
            WHERE is_operational AND (has_open_session OR has_active_ticket)
        )::BIGINT AS occupied_slots,
        -- Operational slots: total operational slots excluding maintenance (denominator)
        COUNT(slot_id) FILTER (
            WHERE is_operational
        )::BIGINT AS operational_slots
    FROM slot_live_status
    GROUP BY floor_number
),
active_ticket_stats AS (
    SELECT
        s.floor_number,
        COUNT(t.id)::BIGINT AS active_ticket_count
    FROM ticket t
    JOIN parking_slot s ON s.id = t.slot_id
    WHERE t.deleted_at IS NULL
      AND t.status = 'ACTIVE'
      AND CURRENT_TIMESTAMP >= t.effective_from
      AND CURRENT_TIMESTAMP < t.effective_to
      AND s.deleted_at IS NULL
    GROUP BY s.floor_number
)
SELECT
    fa.floor_number,
    fa.total_slots,
    fa.available_slots,
    fa.occupied_slots,
    COALESCE(ats.active_ticket_count, 0)::BIGINT AS active_ticket_count,
    COALESCE(
        ROUND(
            (fa.occupied_slots::NUMERIC / NULLIF(fa.operational_slots, 0)) * 100,
            2
        ),
        0.00
    ) AS occupancy_rate_percent
FROM floor_aggregated fa
LEFT JOIN active_ticket_stats ats ON ats.floor_number = fa.floor_number
ORDER BY fa.floor_number ASC;

COMMENT ON VIEW v_slot_occupancy_by_floor IS 'Live operational slot occupancy metrics and utilization percentage by floor computed dynamically from current sessions and active ticket windows, excluding maintenance from denominator (SRS 4.7.2 REQ-4.7.2-F04, OQ-63; date-range vehicle traffic by floor is provided by fn_stat_vehicles_by_floor)';


-- 11.4. View v_customer_vehicle_summary (Customer Registered Vehicles and Active Tickets)
-- References: SRS 4.7.2 (REQ-4.7.2-F05 Vehicle chart by customer, image20)
CREATE VIEW v_customer_vehicle_summary AS
WITH customer_vehicle_counts AS (
    SELECT
        customer_id,
        COUNT(id)::BIGINT AS registered_vehicle_count
    FROM vehicle
    WHERE deleted_at IS NULL
    GROUP BY customer_id
),
customer_ticket_counts AS (
    SELECT
        customer_id,
        COUNT(id)::BIGINT AS active_ticket_count
    FROM ticket
    WHERE deleted_at IS NULL
      AND status = 'ACTIVE'
      AND CURRENT_TIMESTAMP >= effective_from
      AND CURRENT_TIMESTAMP < effective_to
    GROUP BY customer_id
)
SELECT
    c.id AS customer_id,
    c.code AS customer_code,
    c.full_name AS customer_name,
    c.phone,
    COALESCE(cvc.registered_vehicle_count, 0)::BIGINT AS registered_vehicle_count,
    COALESCE(ctc.active_ticket_count, 0)::BIGINT AS active_ticket_count
FROM customer c
LEFT JOIN customer_vehicle_counts cvc ON cvc.customer_id = c.id
LEFT JOIN customer_ticket_counts ctc ON ctc.customer_id = c.id
WHERE c.deleted_at IS NULL
ORDER BY registered_vehicle_count DESC, c.code ASC;

COMMENT ON VIEW v_customer_vehicle_summary IS 'All-time registered vehicles and currently active tickets per customer eliminating Cartesian duplication (SRS 4.7.2 REQ-4.7.2-F05; date-range vehicle registration statistics are provided by fn_stat_vehicles_by_customer)';




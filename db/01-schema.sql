-- 2.1. Table account (System login accounts)
-- References: SRS 4.1 (REQ-4.1-F01, REQ-4.1-F02), OQ-02, OQ-03, OQ-55, ADR-0004
CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'EMPLOYEE',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    last_login TIMESTAMPTZ NULL,
    row_version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL,
    deleted_by BIGINT NULL,

    CONSTRAINT ck_account_username_format CHECK (username ~ '^[a-zA-Z0-9_.-]+$'),
    CONSTRAINT ck_account_role_enum CHECK (role IN ('MANAGER', 'EMPLOYEE', 'CUSTOMER')),
    CONSTRAINT fk_account_deleted_by FOREIGN KEY (deleted_by) REFERENCES account (id) ON DELETE RESTRICT
);

COMMENT ON TABLE account IS 'Stores system user login accounts, RBAC permissions and credentials (SRS 4.1, ADR-0004)';
COMMENT ON COLUMN account.id IS 'Surrogate auto-increment primary key (ADR-0004, Rule 05)';
COMMENT ON COLUMN account.username IS 'Unique login username without special characters (REQ-4.1-F01, verbatim SRS message: "Tên đăng nhập không chứa ký tự đặc biệt", OQ-02)';
COMMENT ON COLUMN account.password_hash IS 'Cryptographic password hash via Argon2id / PBKDF2 (REQ-4.1-F02, REQ-4.3.2-F09, REQ-4.3.3-F07, ADR-0004)';
COMMENT ON COLUMN account.role IS 'RBAC authorization role: MANAGER (Quản lý), EMPLOYEE (Nhân viên), CUSTOMER [PROPOSAL] (Khách hàng per OQ-03, OQ-54)';
COMMENT ON COLUMN account.is_active IS 'Account activation status: TRUE (Active), FALSE (Disabled) (SRS 4.1, ADR-0004)';
COMMENT ON COLUMN account.last_login IS 'Timestamp of most recent successful authentication (SRS 4.1, ADR-0004)';
COMMENT ON COLUMN account.row_version IS 'Optimistic concurrency control version counter (MSG-4.3.1-M03, ADR-0003)';
COMMENT ON COLUMN account.created_at IS 'Record creation timestamp with timezone (ADR-0004, Rule 05)';
COMMENT ON COLUMN account.updated_at IS 'Record last modification timestamp with timezone (ADR-0004, Rule 05)';
COMMENT ON COLUMN account.deleted_at IS 'Soft delete timestamp (ADR-0003)';
COMMENT ON COLUMN account.deleted_by IS 'Foreign key referencing account performing soft deletion (ON DELETE RESTRICT) (ADR-0003)';

CREATE UNIQUE INDEX uq_account_username_active ON account (username) WHERE deleted_at IS NULL;
CREATE INDEX idx_account_role ON account (role) WHERE deleted_at IS NULL;


-- 2.2. Table persistent_login_token (Persistent remember-me session tokens)
-- References: SRS 4.1 (REQ-4.1-F03), ADR-0004, OQ-01 (OWASP Persistent Token architecture replacing insecure cookie passwords)
CREATE TABLE persistent_login_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    series VARCHAR(64) NOT NULL,
    token_hash VARCHAR(255) NOT NULL,
    ip_address VARCHAR(45) NULL,
    user_agent TEXT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_persistent_token_account FOREIGN KEY (account_id) REFERENCES account (id) ON DELETE RESTRICT
);

COMMENT ON TABLE persistent_login_token IS 'Persistent login authentication tokens conforming to OWASP guidelines (SRS 4.1 REQ-4.1-F03, ADR-0004)';
COMMENT ON COLUMN persistent_login_token.id IS 'Surrogate auto-increment primary key (ADR-0004, Rule 05)';
COMMENT ON COLUMN persistent_login_token.account_id IS 'Foreign key referencing user account (REQ-4.1-F03, ADR-0004)';
COMMENT ON COLUMN persistent_login_token.series IS 'Unique session series identifier (REQ-4.1-F03, ADR-0004, OQ-01)';
COMMENT ON COLUMN persistent_login_token.token_hash IS 'One-way SHA-256 hash of session verification token (REQ-4.1-F03, ADR-0004)';
COMMENT ON COLUMN persistent_login_token.ip_address IS 'IP address of device initiating login session (REQ-4.1-F03, ADR-0004, OQ-01)';
COMMENT ON COLUMN persistent_login_token.user_agent IS 'Client browser user-agent header string (REQ-4.1-F03, ADR-0004)';
COMMENT ON COLUMN persistent_login_token.expires_at IS 'Expiration timestamp of persistent token (REQ-4.1-F03, ADR-0004)';
COMMENT ON COLUMN persistent_login_token.created_at IS 'Token issuance timestamp (ADR-0004, Rule 05)';
COMMENT ON COLUMN persistent_login_token.last_used_at IS 'Timestamp of most recent token-based authentication (ADR-0004, Rule 05)';

CREATE UNIQUE INDEX uq_persistent_token_series ON persistent_login_token (series);
CREATE INDEX idx_persistent_token_account ON persistent_login_token (account_id);
CREATE INDEX idx_persistent_token_expires ON persistent_login_token (expires_at);


-- 2.3. Table password_reset_token (One-time password reset tokens dispatched via email)
-- References: SRS 4.1 (REQ-4.1-F04), SCO-05 (Tasks_Sprint_1 Task 1)
CREATE TABLE password_reset_token (
